#ifndef __HCI_H
#define __HCI_H

/* ============================================================================
 * HCI.h —— 人机界面显示模块 头文件
 *
 * 对外只暴露：5 个全局变量 + 3 个函数。其他模块写变量，HCI 负责显示。
 *
 * 用法：
 *     LCD_Init();          // 你自己的屏幕初始化
 *     HCI_Init();          // 只调一次：清屏 + 画 5 行静态标签
 *
 *     while (1) {
 *         HCI_Lap1Ms    = ...;      // 功能层随时写这 5 个变量
 *         HCI_ObsCount  = ...;
 *         HCI_Update();             // 主循环反复调，内部 100ms 节流
 *     }
 * ========================================================================== */

#include <stdint.h>

/* ============================================================================
 * 五个显示变量（全局，功能层直接赋值，HCI 只读）
 *
 * 32 位 / 16 位对齐写在 Cortex-M3 上是原子的，单写不需要关中断。
 * 若一次要改多个、且希望屏幕同步显示同一时刻的值，请在调用前短暂关中断。
 * ========================================================================== */

/* 第一圈耗时，单位 ms。0 = 未完成，屏幕显示 "--.-s" */
extern uint32_t HCI_Lap1Ms;

/* 第二圈耗时，单位 ms。0 = 未完成，屏幕显示 "--.-s" */
extern uint32_t HCI_Lap2Ms;

/* 障碍识别次数，显示范围 0~99（超出按 99 显示） */
extern uint16_t HCI_ObsCount;

/* 倒车入库识别次数，显示范围 0~99 */
extern uint16_t HCI_RevCount;

/* 侧方停车识别次数，显示范围 0~99 */
extern uint16_t HCI_SideCount;

/* ============================================================================
 * 接口
 * ========================================================================== */

/* 画 5 行静态标签（中文 + 3 个「次」）并刷新一遍数值。
 * 必须在 LCD 初始化完成之后调用，且只调用一次。 */
void HCI_Init(void);

/* 刷新数值。内部做 100ms 节流 + 值变化检测，主循环里反复调不会重复刷屏。 */
void HCI_Update(void);

/* 强制下一帧全量重绘。重新发车、或屏幕被别的模块画花时使用。 */
void HCI_ForceUpdate(void);

#endif /* __HCI_H */
