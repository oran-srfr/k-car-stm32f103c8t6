/* ============================================================================
 * LapTimer.h —— 圈计时器（靠陀螺仪累积转角判圈）
 *
 * 职责：只做一件事 —— 吃 Yaw 角度，判断跑了几圈，记下每圈耗时。
 *       不读传感器、不写屏幕、不控车。所有依赖都从参数传进来。
 *
 * 判圈规则：
 *     累积转角 到 360° = 第 1 圈
 *     累积转角 到 720° = 第 2 圈 → 置 finished，停表
 *
 * 计时口径：
 *     第 1 圈耗时 = t(360°) - t(发车)
 *     第 2 圈耗时 = t(720°) - t(360°)      ← 第二圈单独耗时，不是累计
 *
 * 用法：
 *     Lap_Init();                                  // 上电一次
 *     Lap_Start(HAL_GetTick());                    // 发车（按键/起跑触发）
 *
 *     // 每收到一帧 MPU6050 的角度就调一次（100Hz）
 *     Lap_FeedYaw(yaw_deg, HAL_GetTick());
 *
 *     // 主循环里偶尔同步给屏幕
 *     LapStatus st;
 *     Lap_GetStatus(&st);
 *     HCI_Lap1Ms = st.lap1_ms;
 *     HCI_Lap2Ms = st.lap2_ms;
 *
 * 注意：
 *   · 本模块不调用 HAL，也不依赖任何外设，可以直接在电脑上用 gcc 跑测试。
 *   · 必须在主循环里调用 Lap_FeedYaw()，不要在中断里调（里面有浮点运算，
 *     压在中断里会拖慢编码器脉冲采集）。
 * ========================================================================== */

#ifndef LAPTIMER_H
#define LAPTIMER_H

#include <stdint.h>
#include <stdbool.h>

/* ============================================================================
 * 可调参数
 * ========================================================================== */

/* 目标圈数：跑满就停表 */
#define LAP_TARGET_LAPS         2u

/* 残余角门限（度）：积攒到这个量就并入累积角。
 * 为什么需要它：模块 100Hz，10ms 一帧。车速慢时每帧只转 0.05°，
 * 如果按「单帧太小就丢弃」处理，慢速转弯会被整条丢掉，永远判不出圈。 */
#define LAP_FLUSH_DEG           0.15f

/* 角速度超过这个值（度/秒）就直接并入，不做门限判断 */
#define LAP_FAST_DPS            5.0f

/* 角速度低于这个值视为「静止」，把残余量按 LAP_REST_LEAK 泄放掉，
 * 防止静止时的噪声积分成假圈 */
#define LAP_REST_DPS            0.5f
#define LAP_REST_LEAK           0.90f

/* 两帧间隔超过这个值（ms）视为数据断流，丢弃增量、重建基准。
 * 否则一次断线会算出巨大增量，直接跳好几圈。 */
#define LAP_DT_MAX_MS           500u

/* Yaw 合理范围上限（度）。超出说明是坏帧（帧错位/校验漏检）。
 * 这个判断同时能拦住 NaN 和 ±Inf：
 *   NaN 参与比较恒为假，指数值比较恒为假，都被判为「不合理」。 */
#define LAP_YAW_ABS_MAX         1.0e4f

/* ============================================================================
 * 状态快照
 * ========================================================================== */
typedef struct {
    bool     running;       /* 正在计时 */
    bool     finished;      /* 已跑满 LAP_TARGET_LAPS 圈 */
    uint8_t  laps;          /* 已完成圈数：0 / 1 / 2 */

    uint32_t lap1_ms;       /* 第一圈耗时，0 = 未完成 */
    uint32_t lap2_ms;       /* 第二圈耗时，0 = 未完成 */
    uint32_t elapsed_ms;    /* 发车至今（跑满后停止增长）*/

    float    accum_deg;     /* 累积转角，带符号 */
    float    pending_deg;   /* 尚未并入的残余角 */
    float    rate_dps;      /* 最近一帧的角速度（绝对值）*/
} LapStatus;

/* ============================================================================
 * 接口
 * ========================================================================== */

/* 上电初始化（清零内部状态）*/
void Lap_Init(void);

/* 发车：清空累积角、开始计时。now_ms 传 HAL_GetTick() */
void Lap_Start(uint32_t now_ms);

/* 中途终止：停止计时但保留已测数据 */
void Lap_Stop(void);

/* 喂一帧 Yaw（单位：度，±180 或 0~360 表示都可以，内部自动解卷绕）
 * 每收到一帧 MPU6050 角度数据就调一次，只在主循环里调 */
void Lap_FeedYaw(float yaw_deg, uint32_t now_ms);

/* 更新计时（可选）。主循环里定期调，让 elapsed_ms 实时增长；
 * 不调也不影响判圈和每圈耗时，只是 elapsed_ms 不刷新 */
void Lap_Tick(uint32_t now_ms);

/* 取状态快照 */
void Lap_GetStatus(LapStatus *out);

/* 是否已跑满两圈 */
bool Lap_IsFinished(void);

#endif /* LAPTIMER_H */
